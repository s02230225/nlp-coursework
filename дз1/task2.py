    def split_sentences(text):
        sentences = []
        current_sentence = ""
        i = 0
        n = len(text)
        while i < n:
            current_sentence += text[i]
            if text[i] in '.!?':
                if i + 1 < n and text[i + 1] == ' ':
                    if i + 2 < n:
                        next_char = text[i + 2]
                        if (next_char.isupper() and 'А' <= next_char <= 'Я') or next_char.isdigit():
                            sentences.append(current_sentence.strip())
                            current_sentence = ""
                            i += 1
                elif i + 1 == n:
                    sentences.append(current_sentence.strip())
                    current_sentence = ""  # ДОБАВЛЕНО: очищаем current_sentence
            i += 1
        if current_sentence.strip():
            sentences.append(current_sentence.strip())
        return sentences


