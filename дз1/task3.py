    # Известно, что слова, оканчивающиеся на "ок" (типа "кружок", "замок", "лоток") склоняются одним способом, а слова,
    # оканчивающиеся на "а" ("мама", "рама", "ванна", "корзина") - другим. Вводится слово.  Программа классифицирует слово
    # (на "ок", на "а", другое)  и, если слово принадлежит к первым двум типам,  печатает его в разных падежах, иначе пишет,
    # что тип склонения незнаком.
    # Пример станок:   это станок,  нет станка, к станку, вижу  станок, чем? -  станком, о станке   это станки, много
    # станков, к станкам, вижу станки, чем? - станками, о станках
    # панама:    это панама, нет панамы   и т.д.
    # Со всеми ли словами программа будет работать правильно? Если нет, приведите варианты доработки (можно схематично).


    def decline_ok(word):
        if not word.endswith('ок'):
            return None
        base = word[:-2]
        singular = {
            'именит': word,
            'родит': base + 'ка',
            'дател': base + 'ку',
            'винит': word,
            'творит': base + 'ком',
            'предлож': base + 'ке'
        }
        plural = {
            'именит': base + 'ки',
            'родит': base + 'ков',
            'дател': base + 'кам',
            'винит': base + 'ки',
            'творит': base + 'ками',
            'предлож': base + 'ках'
        }

        return singular, plural


    def decline_a(word):
        if not word.endswith('а'):
            return None
        base = word[:-1]
        singular = {
            'именит': word,
            'родит': base + 'ы',
            'дател': base + 'е',
            'винит': base + 'у',
            'творит': base + 'ой',
            'предлож': base + 'е'
        }
        plural = {
            'именит': base + 'ы',
            'родит': base + '',
            'дател': base + 'ам',
            'винит': base + 'ы',
            'творит': base + 'ами',
            'предлож': base + 'ах'
        }
        return singular, plural


    def print_declension(singular, plural):
        print("Единственное число:")
        for padezh, form in singular.items():
            print(f"  {padezh}. падеж: {form}")
        print("Множественное число:")
        for padezh, form in plural.items():
            print(f"  {padezh}. падеж: {form}")


    word = input("Введите слово: ").lower().strip()
    if word.endswith('ок'):
        print(f"Слово '{word}' типа 'ок'")
        result = decline_ok(word)
        if result:
            singular, plural = result
            print_declension(singular, plural)
    elif word.endswith('а'):
        print(f"Слово '{word}' типа 'а'")
        result = decline_a(word)
        if result:
            singular, plural = result
            print_declension(singular, plural)
    else:
        print(f"Неизвестный тип слова '{word}'")

