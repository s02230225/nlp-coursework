if __name__ == "__main__":
    import nltk

    def parse_sentences(text):
        i = 1
        for sentence in nltk.sent_tokenize(text, language="russian"):
            print(i, "  ", sentence)
            i += 1


    punctuation_marks = """
    Да? Ого! Ну, этого просто не может быть?! Расскажешь потом... \
    Бледно-серое небо светлело, холодело, синело; \
    звёзды то мигали слабым светом, то исчезали; \
    отсырела земля, запотели листья, кое-где стали раздаваться живые звуки, голоса. \
    Лето - это маленькая жизнь. \
    'Буду завтра' - сказал он.
        """
     
    print('-' * 40)
    print('1. Знаки препинания')
    parse_sentences(punctuation_marks) # проверка различных знаков препинания
    print('-' * 40)

    shortening = """
    Ключи и 15руб. Джеймс передал мне сегодня утром. \
    Ключи и 15руб. Иван передал мне сегодня утром.
    Федеральное государственное бюджетное образовательное учреждение высшего образования \
    «Московский государственный университет имени М. В. Ломоносова». \
    По данному адресу располагается техникум им. И.И.Иванова.
    """

    print('-' * 40)
    print('2. Сокращения')
    parse_sentences(shortening) # проверка сокращений
    print('-' * 40)

    direct_speech = """
    		На записке был текст: "Привет. Буду утром." \
      		"Привет. Как дела?" - сказал он. \
    		«Не могу дождаться летних каникул», — воскликнул Петя.
    		"""

    print('-' * 40)
    print('3. Прямая речь')
    parse_sentences(direct_speech) # прямая речь
    print('-' * 40)

    alpha_num = """
    		Данная модель имеет название 1BDCS23 в каталоге. \
    		R2-D2 один из моих самых любимых персонажей Звёздных войн! \
    		У моего отца был старый ВАЗ21001, который до сих пор пылится в гараже.	
    		"""

    print('-' * 40)
    print('4. Цифро-буквенные комбинации')
    parse_sentences(alpha_num) # цифро-буквенные комбинации
    print('-' * 40)

    dates = """
    		Мои бабушка и дедушка родились 29.02.1946 и 31.12.1950. \
    		Внизу записки стояла дата: 22.04.2004. \
    		04.03.2010 всем необходимо явится на оргсобрание!
    		"""

    print('-' * 40)
    print('5. Даты')
    parse_sentences(dates) # Даты
    print('-' * 40)

    floating_point = """
    		Это яблоко я купил в "Пятерочке" за 20.50руб. \
            Число пи равно 3.14159265...
    		"""

    print('-' * 40)
    print('6. Числа с плавающей запятой')
    parse_sentences(floating_point) # Числа с плавающей запятой
    print('-' * 40)

    mixed = """
    		Данная гос. корпорация им. И.И.Иванова, осуществляет выпуск моделей ГПТ-122У от 14.12.1977. \
    		'Ты пойдешь со мной в кино 10.07.2010, Витя?' - спросил я у него.
    		"""

    print('-' * 40)
    print('7. Комбинации всего вышеперчисленного')
    parse_sentences(mixed) # Комбинации
    print('-' * 40)
